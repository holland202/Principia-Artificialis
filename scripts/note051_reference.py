import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path

# ---------------------------------------------------------------------------
# Core dynamics
# ---------------------------------------------------------------------------

def escape_time(c, z0, max_iter=200, R=2.0):
    """Return iteration count at which |z| exceeds R, or max_iter if bounded."""
    z = z0.copy()
    escape = np.full(z.shape, max_iter, dtype=int)
    active = np.ones(z.shape, dtype=bool)
    for n in range(max_iter):
        z[active] = z[active]**2 + c
        escaped = active & (np.abs(z) > R)
        escape[escaped] = n
        active &= ~escaped
        if not active.any():
            break
    return escape

def lyapunov_estimate(c, z0, n_iter=100):
    """Average log| f'(z) | = log|2z| along the orbit (finite-time Lyapunov)."""
    z = z0.copy()
    lyap = np.zeros(z.shape, dtype=float)
    active = np.ones(z.shape, dtype=bool)
    for _ in range(n_iter):
        z[active] = z[active]**2 + c
        # avoid log(0)
        absz = np.abs(z)
        contrib = np.zeros_like(absz)
        mask = active & (absz > 1e-12)
        contrib[mask] = np.log(2.0 * absz[mask])
        lyap += contrib
        active &= (absz <= 2.0)
    return lyap / n_iter

def bounded_fraction(c, grid_size=400, max_iter=150, lim=1.6):
    """Fraction of a uniform grid that remains bounded up to max_iter."""
    xs = np.linspace(-lim, lim, grid_size)
    ys = np.linspace(-lim, lim, grid_size)
    X, Y = np.meshgrid(xs, ys)
    Z = X + 1j*Y
    esc = escape_time(c, Z, max_iter=max_iter)
    return np.mean(esc == max_iter)

# ---------------------------------------------------------------------------
# Figure generation
# ---------------------------------------------------------------------------

def render_julia(c, filename, grid_size=700, max_iter=200, lim=1.6):
    xs = np.linspace(-lim, lim, grid_size)
    ys = np.linspace(-lim, lim, grid_size)
    X, Y = np.meshgrid(xs, ys)
    Z = X + 1j*Y
    esc = escape_time(c, Z, max_iter=max_iter)

    fig, ax = plt.subplots(figsize=(6, 6), dpi=150)
    # log-scaled escape time for visual richness
    im = ax.imshow(np.log(esc + 1), extent=[-lim, lim, -lim, lim],
                   cmap="turbo", origin="lower")
    ax.set_title(f"Julia set  c = {c.real:.4f}{c.imag:+.4f}i", fontsize=11)
    ax.set_xlabel("Re(z)")
    ax.set_ylabel("Im(z)")
    fig.colorbar(im, ax=ax, fraction=0.046, label="log(escape time + 1)")
    Path(filename).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(filename, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"Wrote {filename}")

def mandelbrot_slice(real_values, max_iter=150):
    """Bounded fraction along a real slice of parameter space."""
    fracs = []
    for x in real_values:
        fracs.append(bounded_fraction(x + 0j, grid_size=250, max_iter=max_iter))
    return np.array(fracs)

