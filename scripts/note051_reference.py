def main():
    print("=== Note #051 Reference Script ===")
    print("All numbers below are generated by this code.\n")

    # Representative parameters
    params = {
        "disk (c=0)": 0+0j,
        "inside M (c=-0.75)": -0.75+0j,
        "near boundary": -0.75+0.1j,
        "outside M (Cantor-like)": -0.8+0.2j,
    }

    print("Bounded fraction on 400x400 grid (max_iter=150):")
    for name, c in params.items():
        mu = bounded_fraction(c)
        print(f"  {name:30s}  μ ≈ {mu:.4f}")

    print("\nFinite-time Lyapunov estimates (sample of 200 random seeds):")
    rng = np.random.default_rng(42)
    seeds = (rng.random(200) + 1j*rng.random(200)) * 1.2 - 0.6 - 0.6j
    for name, c in params.items():
        ly = lyapunov_estimate(c, seeds, n_iter=80)
        # only average over orbits that have not yet escaped
        finite = ly[np.isfinite(ly)]
        print(f"  {name:30s}  mean λ ≈ {np.mean(finite):.4f}")

    # Real-axis scan across the main cardioid / period-2 bulb boundary
    print("\nReal-axis scan of bounded fraction (Mandelbrot boundary probe):")
    reals = np.linspace(-1.0, 0.3, 14)
    fracs = mandelbrot_slice(reals)
    for x, f in zip(reals, fracs):
        print(f"  c = {x:+.3f}   μ ≈ {f:.3f}")

    # Figures
    print("\nGenerating figures...")
    render_julia(0+0j, "figures/note051_julia_c0.png")
    render_julia(-0.75+0j, "figures/note051_julia_c-0.75.png")
    render_julia(-0.8+0.2j, "figures/note051_julia_cantor.png")
    render_julia(-0.12+0.75j, "figures/note051_julia_dendrite.png")

    # Simple bifurcation-style plot of bounded fraction
    fig, ax = plt.subplots(figsize=(7, 3.5), dpi=150)
    ax.plot(reals, fracs, "o-", color="#1f77b4")
    ax.axvline(-0.75, color="gray", ls="--", label="approx. boundary region")
    ax.set_xlabel("Real part of c")
    ax.set_ylabel("Bounded fraction μ")
    ax.set_title("Bounded fraction along real slice of parameter space")
    ax.legend()
    ax.grid(True, alpha=0.3)
    fig.savefig("figures/note051_mandelbrot_slice.png", bbox_inches="tight")
    plt.close(fig)
    print("Wrote figures/note051_mandelbrot_slice.png")

    print("\nVincit Omnia Veritas")

if __name__ == "__main__":
    main()
